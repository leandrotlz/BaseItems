export function generatorString() {
    return "baseitems.pages.dev " + new Date().toISOString().slice(0, 10);
}

export function generatedByComment() {
    const dashes = "// " + "-".repeat(99);
    return [dashes, "// Generated by " + generatorString(), dashes, ""];
}

export function detailLabel(item) {
    const parts = [];
    if (item.DisplayTabName) parts.push(item.DisplayTabName);
    if (item.DisplayName) parts.push(item.DisplayName);
    return (parts.length > 0 ? parts.join(' > ') + ' ' : '') + `(${item.Name})`;
}

export function searchTokens(text) {
    const tokens = [];
    if (typeof text !== 'string') return tokens;
    for (const part of text.split(',')) {
        const token = part.trim();
        if (token) tokens.push(token);
        if (tokens.length >= 32) break;
    }
    return tokens;
}

export function searchItems(displayHelp, tokens) {
    if (!Array.isArray(tokens) || tokens.length === 0) return true;
    const haystack = (displayHelp ?? "").toLowerCase();
    return tokens.every(token => haystack.includes(token.toLowerCase()));
}

export function countRepeats(items) {
    const counts = new Map();
    for (const item of items) {
        counts.set(item, (counts.get(item) ?? 0) + 1);
    }
    return counts;
}
